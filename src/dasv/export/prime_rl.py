"""Prime Intellect `prime-rl` + `verifiers` v1 split & config exporter (SDD-05, FEAT-18)."""

from __future__ import annotations

import json
from collections.abc import Sequence
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, Field

from dasv.export.common import (
    ExportResult,
    compute_export_manifest_sha,
    resolve_verifier_ref,
)
from dasv.profile.signal_profiler import CurriculumEntry


class PrimeRLTaskRef(BaseModel):
    """Single certified task entry inside a `prime-rl` Taskset split."""

    task_id: str
    root_path: str
    standard: str
    verifier_ref: str
    bucket: str
    pass_at_1: float
    sampler_weight: float


class PrimeRLSplitManifest(BaseModel):
    """Filtered `prime-rl` split manifest pinning certified GOLDILOCKS tasks."""

    schema_version: Literal["1.0.0"] = "1.0.0"
    manifest_sha: str
    base_model: str
    selected_task_ids: list[str] = Field(default_factory=list[str])
    tasks: list[PrimeRLTaskRef] = Field(default_factory=list[PrimeRLTaskRef])


def _render_rl_config_toml(manifest: PrimeRLSplitManifest) -> str:
    quoted_ids = ", ".join(json.dumps(tid) for tid in manifest.selected_task_ids)
    return (
        "# Auto-generated by dasv export --format prime_rl (certified GOLDILOCKS split)\n"
        "[metadata]\n"
        f'schema_version = "{manifest.schema_version}"\n'
        f'dasv_manifest_sha = "{manifest.manifest_sha}"\n\n'
        "[model]\n"
        f"name = {json.dumps(manifest.base_model)}\n\n"
        "[environment]\n"
        f"task_ids = [{quoted_ids}]\n"
        'split = "dasv_goldilocks"\n'
        "clean_image_grading = true\n\n"
        "[training]\n"
        'objective = "dr_grpo"\n'
        "prompts_per_step = 4\n"
        "group_size = 8\n"
        "dynamic_sampling = true\n"
    )


def export_prime_rl(
    entries: Sequence[CurriculumEntry],
    out_path: Path,
    *,
    emit_toml: bool = True,
) -> ExportResult:
    """Export certified curriculum entries to `prime-rl` JSON split + `rl_config.toml`."""
    task_refs = [
        PrimeRLTaskRef(
            task_id=e.task_id,
            root_path=e.root_path,
            standard=e.standard,
            verifier_ref=resolve_verifier_ref(e),
            bucket=e.bucket.value,
            pass_at_1=e.pass_at_1,
            sampler_weight=e.recommended_sampler_weight,
        )
        for e in entries
    ]
    manifest_sha = compute_export_manifest_sha(task_refs)
    base_model = entries[0].base_model if entries else "unknown"
    manifest = PrimeRLSplitManifest(
        manifest_sha=manifest_sha,
        base_model=base_model,
        selected_task_ids=[t.task_id for t in task_refs],
        tasks=task_refs,
    )

    target_json = (
        out_path / "prime_rl_split.json" if (out_path.is_dir() or not out_path.suffix) else out_path
    )
    target_json.parent.mkdir(parents=True, exist_ok=True)
    target_json.write_text(manifest.model_dump_json(indent=2) + "\n", encoding="utf-8")

    companions: list[Path] = []
    if emit_toml:
        toml_path = target_json.parent / "rl_config.toml"
        toml_path.write_text(_render_rl_config_toml(manifest), encoding="utf-8")
        companions.append(toml_path)

    return ExportResult(
        format="prime_rl",
        output_path=target_json,
        companion_paths=companions,
        record_count=len(task_refs),
        manifest_sha=manifest_sha,
    )
